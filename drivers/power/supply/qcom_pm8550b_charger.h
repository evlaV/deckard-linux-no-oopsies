#define CHGR2_QPH2_RT_STS_VIN_HI_MASK BIT(2)
#define CHGR2_QPH2_RT_STS_QPH1_ON_MASK BIT(4)
#define CHGR2_QPH2_RT_STS_QPH2_ON_MASK BIT(5)

#define CHGR2_QPH2_CHG_CTRL (0x42)
